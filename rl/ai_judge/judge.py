def run_compare(a):
    """judge.py compare: the formal paired comparison. Exit 0 complete, 2 failed, 3 inconclusive (data problems); 1 = did not run (unreadable input, wrong
    executable, internal error). A report written to --out is replaced at the start by a 'did_not_finish' stub, so a run that dies never leaves an older 'complete'
    result at that path."""
    inputs = [a.positions, a.references, a.eligibility, *a.results]
    if a.out:  # the first things that can stop the run: --out must not be an input and must be writable; THEN the stub replaces whatever result was there
        if os.path.exists(a.out) and any(os.path.exists(p) and os.path.samefile(p, a.out) for p in inputs):
            sys.exit(f'--out {a.out} is one of the input files: the report would overwrite it')
        if not os.path.isdir(os.path.dirname(os.path.abspath(a.out))):
            sys.exit(f'--out {a.out}: its directory does not exist')
        _write_report(a.out, {'schema': formal.SCHEMA, 'status': 'did_not_finish', 'analysis': None,
                              'problems': [{'kind': 'did_not_finish', 'position': None, 'bot': None, 'run': None, 'detail': 'the comparison started but never wrote its result: this file is not a result'}]})
    if a.prompt != 'v1':
        sys.exit('compare re-renders the frozen prompt (v1); it does not take --prompt')
    for p in inputs:
        if not os.path.exists(p):
            sys.exit(f'input file not found: {p}')
    positions = load_positions(a.positions)
    ids = resolve_ids(a, positions)
    if not ids:
        sys.exit('no positions: give --ids, --id or --set')
    try:
        return _run_compare(a, positions, ids)
    except (SystemExit, KeyboardInterrupt):
        raise
    except Exception as e:  # a defect or an input nobody foresaw: no result, said so in the report file, exit 1 (never a half result)
        msg = f'{type(e).__name__}: {e}'
        if a.out:
            _write_report(a.out, {'schema': formal.SCHEMA, 'status': 'failed', 'analysis': None, 'problems': [{'kind': 'internal_error', 'position': None, 'bot': None, 'run': None, 'detail': msg}]})
        print(f'COMPARISON DID NOT FINISH (internal error, no result): {msg}', file=sys.stderr)
        return 1


def _run_compare(a, positions, ids):
    try:
        references = formal.load_json(a.references)
        eligibility = formal.load_json(a.eligibility)
    except (OSError, ValueError) as e:
        sys.exit(f'cannot read the references / eligibility file: {e}')
    rows, read_problems, results_sha = read_rows(a.results)
    seeds, seed_problems = parse_seeds(a.seeds)
    contrasts = parse_contrasts(a.contrasts)
    ident = frozen_identity()
    experiment = []
    if a.allow_unfrozen:
        experiment.append('--allow-unfrozen')
    if a.allow_other_binaries:
        experiment.append('--allow-other-binaries')
    if a.min_games < analysis.MIN_GAMES:
        experiment.append(f'--min-games {a.min_games} (< {analysis.MIN_GAMES})')
    if a.resamples < analysis.MIN_FORMAL_RESAMPLES:
        experiment.append(f'--resamples {a.resamples} (< {analysis.MIN_FORMAL_RESAMPLES})')
    if a.world_seed != FROZEN['plan_world_seed'] or (a.max_plans is not None and a.max_plans != FROZEN['max_plans']) or a.compact_above != FROZEN['compact_above']:
        experiment.append('plan-list generation or compact threshold differs from the freeze')
    if os.environ.get('PDL_DB'):
        experiment.append('PDL_DB is set (the card texts may come from another database)')
    baseline_sha = ident['baseline']['binary_sha256'] if not a.allow_other_binaries else None
    if not a.allow_other_binaries:
        got = file_sha256(PLANS_BIN)
        if got != ident['plans_binary_sha256']:
            sys.exit(f"the plan lister {PLANS_BIN} is not the frozen executable ({ident['tag']}): sha256 {got[:16]} != {ident['plans_binary_sha256'][:16]}; "
                     "rebuild it from the frozen source or use --allow-other-binaries for an experiment")
        import freeze_identity
        diffs = freeze_identity.check(ident)
        if diffs:
            sys.exit(f"the code, prompt or executables are not the frozen ones ({ident['tag']}): " + '; '.join(diffs) + ' (--allow-other-binaries is for experiments only)')
    recs = list_plans(ids, a.positions, a.decks, a.world_seed, a.max_plans)
    rendered = {}
    compact_above = a.compact_above if a.allow_unfrozen else FROZEN['compact_above']
    judge_provider, judge_expected = judge_expectation(ident)  # the freeze's judge: the `judge` block of FROZEN.json (frozen-5), else the Anthropic settings of frozen-4 and earlier

    def expect_judge(pid, row):
        """The prompt and reply the judge row must have been answered from, re-rendered now: the frozen settings, or (experiments, --allow-unfrozen) the row's own
        order and prompt version."""
        order = row.get('order') if a.allow_unfrozen else FROZEN['order']
        version = row.get('prompt_version', 'v1') if a.allow_unfrozen else FROZEN['prompt_version']
        k = (pid, repr(order), repr(version))
        if k not in rendered:
            try:
                system, user, shown = render_prompt(positions[pid], recs[pid], order, a.decks, compact_above, version)
                n = len(shown)
                rendered[k] = {'prompt_sha256': prompt_hash(system, user), 'shown': {i: p['n'] for i, p in shown.items()},
                               'parse': (lambda raw, n=n: (lambda r: r['plan'] if r['ok'] else None)(parse_choice(raw, n))),
                               'settings': dict(judge_expected)}
            except Exception as e:  # SystemExit from an unknown order, or whatever a malformed order / version does: a prompt_mismatch problem, never a crash
                rendered[k] = {'error': f'order {order!r}, prompt version {version!r}: {type(e).__name__}: {e}'}
        return rendered[k]

    db = card_database_path()
    run_info = {'formal': not experiment, 'experiment_switches': experiment,
                'freeze': {'tag': ident['tag'], 'fingerprint_now': fingerprint(), 'fingerprint_frozen': ident['fingerprint'], 'judge_provider': judge_provider, 'judge_settings': dict(judge_expected)},
                'executables': {'plans_binary_sha256': file_sha256(PLANS_BIN), 'baseline_sha256_required': baseline_sha},
                'inputs': {'positions_sha256': file_sha256(a.positions), 'references_sha256': file_sha256(a.references), 'eligibility_sha256': file_sha256(a.eligibility),
                           'results_sha256': results_sha, 'decks_sha256': dir_sha256(a.decks), 'card_database': {'path': db, 'sha256': file_sha256(db) if db else None}},
                'plan_list_sha256': {pid: plan_list_sha256(recs[pid]) for pid in ids},
                'generation': {'world_seed': a.world_seed, 'limits': {k: recs[ids[0]]['limits'][k] for k in ('max_plans', 'max_nodes', 'max_steps')}},
                'request': {'bots': a.bots, 'seeds': seeds, 'judge_repeats': a.judge_repeats, 'contrasts': a.contrasts, 'on_problem': a.on_problem,
                            'min_games': a.min_games, 'resamples': a.resamples, 'failed_judge_rows': a.failed_judge_rows}}
    ambiguous = {pid: v for pid, v in label_roundtrip(recs, a.positions, a.decks).items() if v['ambiguous'] or v['unfollowable']}
    run_info['plan_list_label_check'] = {'what': 'positions where some plans\' own labels do not name them (fit several plans or cannot be followed): a bot or recorded move '
                                                 'list using such a label is AMBIGUOUS, and the judge is shown plans that look identical', 'positions': ambiguous}
    # a full-scope point whose recorded (human) plan the positions file says is incomplete is scored as disagreement by every complete bot plan: say so
    warnings = []
    full = eligibility.get('full_scope_ids') if isinstance(eligibility, dict) else None
    for pid in (full if isinstance(full, list) else []):
        pos = positions.get(pid) if isinstance(pid, str) else None
        if pos and (pos.get('his_plan_ended') is False or pos.get('plan_truncated_at') is not None):
            warnings.append(f'{pid}: in the full-scope subset, but the positions file says its recorded plan is incomplete (his_plan_ended={pos.get("his_plan_ended")!r}, '
                            f'plan_truncated_at={pos.get("plan_truncated_at")!r}): a complete plan can only disagree with it')
    # the model (version) the service says answered the judge rows: the freeze names the alias, this is the evidence that one model answered them all
    returned = sorted({r['model_returned'] for r in rows if isinstance(r, dict) and r.get('bot') == 'judge' and isinstance(r.get('model_returned'), str)})
    run_info['judge_models_returned'] = returned
    if len(returned) > 1:
        warnings.append(f'the judge rows were answered by more than one model version: {returned}')
    elif returned and not returned[0].startswith(judge_expected.get('model', '')):
        warnings.append(f"the judge rows were answered by {returned[0]!r}, not by the frozen model {judge_expected.get('model')!r}")
    projects = sorted({r['vertex_project'] for r in rows if isinstance(r, dict) and r.get('bot') == 'judge' and isinstance(r.get('vertex_project'), str)})
    run_info['judge_vertex_projects'] = projects  # provenance (Vertex rows only): the Google Cloud project that answered; not part of the freeze
    if len(projects) > 1:
        warnings.append(f'the judge rows were made under more than one Google Cloud project: {projects}')
    run_info['warnings'] = warnings
    for w in warnings:
        print('WARNING: ' + w, file=sys.stderr)
    if experiment:
        print('EXPERIMENT RUN, not the formal result: ' + '; '.join(experiment), file=sys.stderr)
    position_games = {i: positions[i].get('game') for i in ids}
    try:
        report = formal.compare(rows, ids, a.bots.split(','), seeds, a.judge_repeats, references, recs, lambda items, r: match_plans(items, r, a.positions, a.decks), eligibility,
                                a.on_problem, not a.allow_unfrozen, baseline_sha, expect_judge, contrasts, a.min_games, a.resamples, full_match, run_info, seed_problems,
                                read_problems, position_games, a.failed_judge_rows)
    except formal.BatchFailed as e:
        report = e.report
        report.setdefault('run', run_info)
        report.setdefault('formal', run_info['formal'])
        if a.out:
            _write_report(a.out, report)
        print(f'COMPARISON FAILED: {len(e.problems)} problem(s); no agreement is reported:', file=sys.stderr)
        formal.print_problems(e.problems)
        return formal.exit_code(report)
    report.setdefault('run', run_info)
    report.setdefault('formal', run_info['formal'])
    fj = report.get('failed_judge_rows') or {}
    if fj.get('policy') == 'miss' and report['status'] == 'complete' and fj.get('n_judge_decisions_primary') and fj['n_primary_decisions'] / fj['n_judge_decisions_primary'] > FAILED_SHARE_WARNING:
        msg = (f"{fj['n_primary_decisions']} of {fj['n_judge_decisions_primary']} primary judge decisions had no valid choice and were scored as misses: the judge's score is deflated by them "
               f"(more than {int(FAILED_SHARE_WARNING * 100)}%: look for a systematic fault, for example a cap that is too small or blocked prompts)")
        report['run'].setdefault('warnings', []).append(msg)
        print('WARNING: ' + msg, file=sys.stderr)
    if a.out:
        _write_report(a.out, report)
    if report['status'] != 'complete':
        print(f'COMPARISON {report["status"].upper()}: {len(report["problems"])} problem(s); every expected primary row is listed in the report, no agreement is reported:', file=sys.stderr)
        formal.print_problems(report['problems'])
    else:
        print_analysis(report)
        fj = report.get('failed_judge_rows') or {}
        if fj.get('policy') == 'miss':  # said plainly, not only in the file: how many judge rows had no valid choice and were scored as misses
            print(f"JUDGE ROWS WITHOUT A VALID CHOICE (policy 'miss', counted as misses): {fj['n_primary']} at primary points, {fj['n_diagnostic']} at diagnostic points, of "
                  f"{fj['n_judge_rows_primary']} primary judge rows" + (': ' + '; '.join(f"{r['position']} repeat {r['run']} ({r['stop_reason']}: {str(r['reason'])[:70]})" for r in fj['rows'][:20]) if fj['rows'] else ''))
        dp = (report.get('diagnostic_excluded') or {}).get('problems') or []
        if dp:
            print(f'{len(dp)} problem(s) at points outside the primary selection (they do not affect the numbers above):', file=sys.stderr)
            formal.print_problems(dp)
        print('FORMAL RESULT' if run_info['formal'] else 'EXPERIMENT RESULT (not the formal result: ' + '; '.join(experiment) + ')')
    return formal.exit_code(report)


