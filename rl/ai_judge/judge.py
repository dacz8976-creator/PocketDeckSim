def file_sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def frozen_identity():
    """FROZEN.json: the recorded identity (prompt fingerprint, source hashes, executables) of the current freeze."""
    with open(FROZEN_JSON, encoding='utf-8') as f:
        return json.load(f)


plan_list_sha256 = formal.plan_list_sha256  # the identity of one plan list; every row carries the hash of the list it was made from


def prompt_hash(system, user):
    return hashlib.sha256((system + '\n\0\n' + user).encode('utf-8')).hexdigest()[:16]


