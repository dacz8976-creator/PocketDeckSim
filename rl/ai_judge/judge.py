def _cid(s):
    return ' '.join(s.split()[-2:])


def _deck_ids(deck_key, decks_dir):
    ids = []
    with open(os.path.join(decks_dir, deck_key + '.txt'), encoding='utf-8') as f:
        for line in f:
            w = line.split()
            if len(w) >= 3 and w[0].isdigit():
                ids.append(' '.join(w[-2:]))
    return ids


_DB = None


def card_texts(pos, decks_dir=DEFAULT_DECKS):
    """The exact text (lib/card.py) of every card the player can see or hold: own hand, board, discard, deck list; the opponent's board and Stadium."""
    global _DB
    if _DB is None:
        _DB = {v['id']: (k, v) for k, v in cardlib.load()}
    ids = []

    def add(s):
        if s:
            ids.append(_cid(s))

    me, opp = pos['me'], pos['opp']
    for s in me.get('hand', []) + me.get('discard', []):
        add(s)
    for b in me.get('board', []) + opp.get('board', []):
        add(b['card'])
        for s in b.get('behind', []) + b.get('tools', []):
            add(s)
    for s in opp.get('discard', []):
        add(s)
    if pos.get('stadium'):
        add(pos['stadium']['card'])
    ids += _deck_ids(pos['deck'], decks_dir)
    seen, blocks = set(), []
    for i in ids:
        if i not in _DB:
            continue
        kind, v = _DB[i]
        text = cardlib.fmt(kind, {**v, 'id': '?'}).replace('[?]', '')
        if text in seen:
            continue
        seen.add(text)
        blocks.append(cardlib.fmt(kind, v))
    return blocks


def _plan_text(n, plan, start_board):
    steps = ' -> '.join(plan['steps'])
    changed = [l for l in plan['result']['board'] if l not in start_board]
    fin = plan['final']
    parts = [f'Plan {n}: {steps}.']
    if plan['end'] == 'attack':
        outs = fin.get('outcomes')
        if outs:
            txt = []
            for o in outs:
                body = '; '.join(o['lines']) if o['lines'] else 'no visible change'
                txt.append(f"{int(round(o['p'] * 100))}%: {body}" if len(outs) > 1 else body)
            parts.append('Attack result: ' + ' | '.join(txt) + '.')
        else:
            parts.append(f"Attack result: could not be priced by the engine ({fin.get('unpriced', '?')}); printed damage {fin.get('printed_damage')}.")
    elif plan['end'] == 'chance':
        k = fin.get('kind')
        if k == 'your_deck':
            parts.append(f"Then a chance event: it takes cards from your deck (deck {fin['deck_size_before']} -> {fin['deck_size_after']} cards, hand {fin['hand_size_before']} -> {fin['hand_size_after']}). "
                         "You will see the cards before choosing again.")
        elif k == 'coin_or_random':
            parts.append('Then a chance event (a coin flip or a random pick). The possible outcomes have these chances: '
                         + ', '.join(f'{int(round(p * 100))}%' for p in fin['branch_chances']) + '. You will see the result before choosing again.')
        else:
            parts.append('Then a chance event the engine cannot price from what you can see. You will see the result before choosing again.')
    elif plan['end'] == 'opponent_choice':
        parts.append('Then the opponent must make a choice; you will see it before choosing again.')
    else:
        parts.append('The turn ends.')
    parts.append('Before the last step: ' + ('; '.join(changed) if changed else 'board unchanged') + f". Hand: {', '.join(plan['result']['hand']) or 'empty'}.")
    return ' '.join(parts)


