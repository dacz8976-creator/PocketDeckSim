def load_key():
    k = os.environ.get('ANTHROPIC_API_KEY')
    if k:
        return k
    bashrc = os.path.expanduser('~/.bashrc')
    if os.path.exists(bashrc):
        last = None
        for line in open(bashrc, encoding='utf-8', errors='replace'):
            m = re.match(r'\s*export\s+ANTHROPIC_API_KEY=(.+)$', line.strip())
            if m:
                last = m.group(1).strip().strip('"\'')
        if last:
            return last
    sys.exit('no ANTHROPIC_API_KEY (environment or ~/.bashrc)')


