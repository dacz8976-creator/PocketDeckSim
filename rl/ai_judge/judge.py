# ---------------------------------------------------------------------------------------------------------------------------------- prompt
def _cid(s):
    return ' '.join(s.split()[-2:])


def _deck_ids(deck_key, decks_dir):
    ids = []
    with open(os.path.join(decks_dir, deck_key + '.txt'), encoding='utf-8') as f:
        for line in f:
            w = line.split()
            if len(w) >= 3 and w[0].isdigit():
                ids.append(' '.join(w[-2:]))
    return ids


_DB = None


def card_texts(pos, decks_dir=DEFAULT_DECKS):
    """The exact text (lib/card.py) of every card the player can see or hold: own hand, board, discard, deck list; the opponent's board and Stadium."""
    global _DB
    if _DB is None:
        _DB = {v['id']: (k, v) for k, v in cardlib.load()}
    ids = []

    def add(s):
        if s:
            ids.append(_cid(s))

    me, opp = pos['me'], pos['opp']
    for s in me.get('hand', []) + me.get('discard', []):
        add(s)
    for b in me.get('board', []) + opp.get('board', []):
        add(b['card'])
        for s in b.get('behind', []) + b.get('tools', []):
            add(s)
    for s in opp.get('discard', []):
        add(s)
    if pos.get('stadium'):
        add(pos['stadium']['card'])
    ids += _deck_ids(pos['deck'], decks_dir)
    seen, blocks = set(), []
    for i in ids:
        if i not in _DB:
            continue
        kind, v = _DB[i]
        text = cardlib.fmt(kind, {**v, 'id': '?'}).replace('[?]', '')
        if text in seen:
            continue
        seen.add(text)
        blocks.append(cardlib.fmt(kind, v))
    return blocks


def _plan_text(n, plan, start_board):
    steps = ' -> '.join(plan['steps'])
    changed = [l for l in plan['result']['board'] if l not in start_board]
    fin = plan['final']
    parts = [f'Plan {n}: {steps}.']
    if plan['end'] == 'attack':
        outs = fin.get('outcomes')
        if outs:
            txt = []
            for o in outs:
                body = '; '.join(o['lines']) if o['lines'] else 'no visible change'
                txt.append(f"{int(round(o['p'] * 100))}%: {body}" if len(outs) > 1 else body)
            parts.append('Attack result: ' + ' | '.join(txt) + '.')
        else:
            parts.append(f"Attack result: could not be priced by the engine ({fin.get('unpriced', '?')}); printed damage {fin.get('printed_damage')}.")
    elif plan['end'] == 'chance':
        k = fin.get('kind')
        if k == 'your_deck':
            parts.append(f"Then a chance event: it takes cards from your deck (deck {fin['deck_size_before']} -> {fin['deck_size_after']} cards, hand {fin['hand_size_before']} -> {fin['hand_size_after']}). "
                         "You will see the cards before choosing again.")
        elif k == 'coin_or_random':
            parts.append('Then a chance event (a coin flip or a random pick). The possible outcomes have these chances: '
                         + ', '.join(f'{int(round(p * 100))}%' for p in fin['branch_chances']) + '. You will see the result before choosing again.')
        else:
            parts.append('Then a chance event the engine cannot price from what you can see. You will see the result before choosing again.')
    elif plan['end'] == 'opponent_choice':
        parts.append('Then the opponent must make a choice; you will see it before choosing again.')
    else:
        parts.append('The turn ends.')
    parts.append('Before the last step: ' + ('; '.join(changed) if changed else 'board unchanged') + f". Hand: {', '.join(plan['result']['hand']) or 'empty'}.")
    return ' '.join(parts)


COMPACT_LEGEND = """Plans are written as short move labels joined by ' > ':
  @0 is the Active Pokémon, @1 @2 @3 are Bench 1 2 3.
  Attach:1Darkness@2 zone = attach this turn's Darkness Energy from the Energy Zone to Bench 2;  Attach:... fx = an Energy attached by a card effect;
  Play:X = play card X (a Tool, Stadium or Pokémon is then placed with a following Tool:X@i, Place:X@i step);  Evolve:X@i = evolve the Pokémon at @i into X;
  Retreat:i = swap the Active with Bench i;  Ability@i = use the Ability of the Pokémon at @i;  Attack:name = attack (the turn ends);  EndTurn = end the turn;
  UseStadium = use the Stadium's once-per-turn effect;  anything else is a choice made inside a card effect.
  [chance] means the plan stops at its last step because that step is a draw, a search or a coin flip: you will see the result and choose again.
  [opp ...] after an attack is what that attack does to the opponent's board by the engine's own calculation (several results are given with their chances)."""


def _plan_compact(n, plan):
    s = f"{n}: {' > '.join(plan['labels'])}"
    fin = plan['final']
    if plan['end'] == 'attack':
        outs = fin.get('outcomes')
        if outs:
            s += ' [opp ' + ' | '.join((f"{int(round(o['p'] * 100))}% " if len(outs) > 1 else '') + ('; '.join(l.replace('Opponent: ', '') for l in o['lines'] if l.startswith('Opponent')) or 'no change') for o in outs) + ']'
        else:
            s += f" [unpriced; printed {fin.get('printed_damage')}]"
    elif plan['end'] == 'chance':
        s += ' [chance]'
    elif plan['end'] == 'opponent_choice':
        s += ' [opponent chooses]'
    return s


def order_plans(plans, order):
    plans = list(plans)
    if order == 'reverse':
        plans.reverse()
    elif order.startswith('shuffle:'):
        import random
        random.Random(int(order.split(':', 1)[1])).shuffle(plans)
    elif order != 'forward':
        sys.exit(f'unknown --order {order}')
    return plans


COMPACT_ABOVE = 80  # more plans than this: one short line per plan (labels only) so a long list stays affordable


def render_prompt(pos, rec, order='forward', decks_dir=DEFAULT_DECKS, compact_above=COMPACT_ABOVE):
    """Returns (system, user, shown) where `shown` maps the number printed in the prompt to the plan record."""
    s = rec['start']
    me, opp = s['me'], s['opp']
    L = []
    L.append(f"It is turn {pos['turn_count']} of the game (your turn number {pos.get('his_turn', '?')}). You are the player on the move.")
    L.append(f"Points (3 wins): you {s['points'][0]}, opponent {s['points'][1]}.")
    ez, ez_next = s['energy_zone']
    L.append(f'Energy Zone: you can attach one {ez} Energy this turn; the next one is {ez_next}.' if ez else 'Energy Zone: you have no Energy to attach this turn (first turn).')
    if s.get('stadium'):
        L.append(f"Stadium in play: {s['stadium']} (played by {'you' if s.get('stadium_owner') == 0 else 'the opponent'}).")
    kos = pos['me'].get('knockouts')
    if kos is not None:
        L.append(f'Your Pokémon Knocked Out so far this game: {kos}.')
    if pos.get('turn_effects'):
        L.append('Effects active this turn: ' + json.dumps(pos['turn_effects']) + '.')
    L.append('\nYOUR BOARD')
    L += ['  ' + l for l in me['board']]
    L.append('Your hand: ' + (', '.join(me['hand']) or 'empty'))
    L.append('Your discard pile: ' + (', '.join(me['discard']) or 'empty') + (f"; discarded Energy: {', '.join(me['discard_energy'])}" if me['discard_energy'] else ''))
    deck = ', '.join(f'{n} x {c}' for c, n in sorted(me['unseen_deck'].items()))
    L.append(f"Your deck: {me['deck_size']} cards, order unknown. They are: {deck}.")
    L.append('\nOPPONENT')
    L += ['  ' + l for l in opp['board']]
    L.append(f"Opponent hand: {opp['hand_count']} cards (hidden). Opponent deck: {opp['deck_count']} cards. Opponent discard pile: " + (', '.join(opp['discard']) or 'empty') + '.')
    L.append("The opponent's deck list is unknown to you.")
    L.append('\nCARD TEXT (exact)')
    L += card_texts(pos, decks_dir)
    plans = order_plans(rec['plans'], order)
    compact = len(plans) > compact_above
    L.append(f'\nPLANS ({len(plans)} legal whole-turn plans' + (f', in short form because there are more than {compact_above}' if compact else '') + ')'
             + (f"{' (the list was cut at ' + str(rec['limits']['max_plans']) + ' plans)' if rec['capped'] else ''}"))
    if compact:
        L.append(COMPACT_LEGEND)
        L.append('Your board and hand before any plan are as shown above.')
    shown = {}
    for i, p in enumerate(plans, 1):
        shown[i] = p
        L.append(_plan_compact(i, p) if compact else _plan_text(i, p, me['board']))
    L.append('\n' + ANSWER_FORMAT)
    return SYSTEM, '\n'.join(L), shown


def estimate_tokens(*texts):
    """No network: about 3.4 characters per token for this kind of text (plain estimate; use --count-tokens for the API's exact count)."""
    return int(sum(len(t) for t in texts) / 3.4) + 1


# ---------------------------------------------------------------------------------------------------------------------------------- parser
def parse_choice(text, n_plans):
    """The reply must carry 'PLAN: <number>' (1..n_plans) and a one-line 'REASON: ...'. Returns {'ok', 'plan', 'reason', 'error'}."""
    nums = [int(m.group(1)) for m in re.finditer(r'(?im)^\s*\**\s*PLAN\s*\**\s*[:=\-]\s*\**\s*(?:plan\s*)?#?\s*(\d+)', text)]
    reason_m = re.search(r'(?im)^\s*\**\s*REASON\s*\**\s*[:=\-]\s*(.+?)\s*$', text)
    reason = reason_m.group(1).strip() if reason_m else None
    if not nums:
        return {'ok': False, 'plan': None, 'reason': reason, 'error': 'no PLAN line'}
    if len(set(nums)) > 1:
        return {'ok': False, 'plan': None, 'reason': reason, 'error': f'several different PLAN lines {sorted(set(nums))}'}
    n = nums[0]
    if not 1 <= n <= n_plans:
        return {'ok': False, 'plan': None, 'reason': reason, 'error': f'plan {n} is not in 1..{n_plans}'}
    return {'ok': True, 'plan': n, 'reason': reason, 'error': None if reason else 'no REASON line (choice kept)'}


# ---------------------------------------------------------------------------------------------------------------------------------- API
def load_key():
    k = os.environ.get('ANTHROPIC_API_KEY')
    if k:
        return k
    bashrc = os.path.expanduser('~/.bashrc')
    if os.path.exists(bashrc):
        last = None
        for line in open(bashrc, encoding='utf-8', errors='replace'):
            m = re.match(r'\s*export\s+ANTHROPIC_API_KEY=(.+)$', line.strip())
            if m:
                last = m.group(1).strip().strip('"\'')
        if last:
            return last
    sys.exit('no ANTHROPIC_API_KEY (environment or ~/.bashrc)')


def call_claude(system, user, model=MODEL, max_tokens=300, temperature=None, timeout=120):
    body = {'model': model, 'max_tokens': max_tokens, 'system': system, 'messages': [{'role': 'user', 'content': user}]}
    if temperature is not None:
        body['temperature'] = temperature
    req = urllib.request.Request('https://api.anthropic.com/v1/messages', data=json.dumps(body).encode(), method='POST',
                                 headers={'x-api-key': load_key(), 'anthropic-version': '2023-06-01', 'content-type': 'application/json'})
    t0 = time.time()
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            j = json.load(r)
    except urllib.error.HTTPError as e:
        sys.exit(f'API error {e.code}: {e.read().decode()[:500]}')
    text = ''.join(b.get('text', '') for b in j.get('content', []) if b.get('type') == 'text')
    u = j.get('usage', {})
    return text, u, round(time.time() - t0, 2), j.get('model', model)


def cost_of(model, usage):
    pin, pout = PRICES.get(model, PRICES.get(MODEL, (3.0, 15.0)))
    tin = usage.get('input_tokens', 0) + usage.get('cache_creation_input_tokens', 0) * 1.25 + usage.get('cache_read_input_tokens', 0) * 0.1
    usd = tin * pin / 1e6 + usage.get('output_tokens', 0) * pout / 1e6
    return {'input_tokens': usage.get('input_tokens'), 'output_tokens': usage.get('output_tokens'), 'cache_creation_input_tokens': usage.get('cache_creation_input_tokens', 0),
            'cache_read_input_tokens': usage.get('cache_read_input_tokens', 0), 'usd': round(usd, 5), 'price_per_mtok': [pin, pout], 'price_note': PRICE_NOTE}


# ---------------------------------------------------------------------------------------------------------------------------------- records
def record(position, bot, plan, cut, **extra):
    r = {'schema': SCHEMA, 'position': position, 'bot': bot, 'seed': None, 'plan': plan, 'cut': cut}
    r.update(extra)
    return r


def judge_one(pid, positions, recs, order, live, model, temperature=None, decks_dir=DEFAULT_DECKS, compact_above=COMPACT_ABOVE):
    pos, rec = positions[pid], recs[pid]
    system, user, shown = render_prompt(pos, rec, order, decks_dir, compact_above)
    est = estimate_tokens(system, user)
    base = dict(order=order, n_plans=len(shown), capped=rec['capped'], total_plans_found=rec['total_found'], model=model, prompt_tokens_estimate=est, dry_run=not live,
                prompt_form='compact' if len(shown) > compact_above else 'full')
    if not live:
        return record(pid, 'judge', None, None, plan_number=None, reason=None, cost=None, **base), system, user
    text, usage, secs, model_used = call_claude(system, user, model, temperature=temperature)
    parsed = parse_choice(text, len(shown))
    plan = shown[parsed['plan']] if parsed['ok'] else None
    r = record(pid, 'judge', plan['labels'] if plan else None, plan['end'] if plan else None, plan_number=plan['n'] if plan else None, shown_number=parsed['plan'],
               reason=parsed['reason'], parse_error=parsed['error'], raw=text, seconds=secs, cost=cost_of(model_used, usage), **base)
    return r, system, user


# ---------------------------------------------------------------------------------------------------------------------------------- bots through pg_pos
def run_pg_pos(bot, ids, seeds, recs, positions_path=DEFAULT_POSITIONS, decks_dir=DEFAULT_DECKS, bin_path=PG_POS_BIN):
    """km3 / kx3 (any bot code pg_pos knows) on positions. pg_pos plays the bot's whole turn; the record keeps what it played (`plan_full`) and the same
    plan in the judge's terms (`plan`: cut after the first chance step, nothing after an attack) with the listed plan's number."""
    rows = []
    for pid in ids:
        cmd = [bin_path, '--positions', positions_path] + deck_args(decks_dir) + ['--seeds', ','.join(map(str, seeds)), '--bot', bot, '--only', pid]
        r = subprocess.run(cmd, capture_output=True, text=True)
        for line in r.stdout.splitlines():
            j = json.loads(line)
            if j.get('kind') == 'free':
                rows.append((pid, j))
    matched = match_plans([(pid, f"{pid}|{j['seed']}", j['plan']) for pid, j in rows], recs, positions_path, decks_dir)
    out = []
    for pid, j in rows:
        n, err = matched[f"{pid}|{j['seed']}"]
        plan = canonical_plan(j['plan'], recs[pid])
        end = recs[pid]['plans'][n - 1]['end'] if n else None
        rec = record(pid, bot, plan, end, plan_number=n, match_error=err, plan_full=j['plan'], pg_pos_cut=j['cut'], cost=None, dry_run=False)
        rec['seed'] = j['seed']
        out.append(rec)
    return out


def _norm(l):  # recorded plans name a Place or an Ability without the slot number
    return l.split('@')[0] if l.startswith(('Place:', 'Ability')) else l


def canonical_plan(labels, rec):
    """A bot's or a recording's move list, put in the plan list's terms: cut after its first chance step (the judge decides again there), and nothing
    after an attack. The closing EndTurn of a plan that did not attack stays out of the comparison key (see match_plan)."""
    chance_labels = {_norm(p['labels'][-1]) for p in rec['plans'] if p['end'] == 'chance'}
    out = []
    for l in labels:
        out.append(l)
        if _norm(l) in chance_labels or l.startswith('Attack:'):
            break
    return out


def replay(items, positions_path=DEFAULT_POSITIONS, decks_dir=DEFAULT_DECKS, world_seed=1, bin_path=PLANS_BIN):
    """Replays move lists through the engine (the same step rules as the plan lister) and returns {tag: [plan keys]}. items = [(position id, tag, labels)].
    A move list is followed up to its first chance step or its attack; a list that ends first is ended with End the turn; a step the list does not name
    but the engine forces (one legal action) is taken. A list that cannot be followed gets an error text instead of keys."""
    import tempfile
    with tempfile.NamedTemporaryFile('w', suffix='.jsonl', delete=False) as f:
        for pid, tag, labels in items:
            f.write(json.dumps({'id': pid, 'tag': tag, 'labels': labels}) + '\n')
        path = f.name
    try:
        cmd = [bin_path, '--positions', positions_path] + deck_args(decks_dir) + ['--world-seed', str(world_seed), '--replay', path]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            sys.exit(f'judge_plans --replay failed: {r.stderr[-1500:]}')
    finally:
        os.unlink(path)
    out = {}
    for line in r.stdout.splitlines():
        j = json.loads(line)
        out[j['tag']] = j['keys'] if j['ok'] else j['error']
    return out


def number_for(rec, keys):
    """The listed plan whose key is among `keys` (None when the move list could not be followed or reaches no listed plan)."""
    if not isinstance(keys, list):
        return None
    by_key = {p['key']: p['n'] for p in rec['plans']}
    for k in keys:
        if k in by_key:
            return by_key[k]
    return None


def match_plans(items, recs, positions_path=DEFAULT_POSITIONS, decks_dir=DEFAULT_DECKS):
    """items = [(position id, tag, labels)] -> {tag: (plan number or None, error text or None)}."""
    keys = replay(items, positions_path, decks_dir)
    out = {}
    for pid, tag, _ in items:
        k = keys.get(tag)
        out[tag] = (number_for(recs[pid], k), k if isinstance(k, str) else (None if number_for(recs[pid], k) else 'reaches no listed plan (capped list?)'))
    return out


def agrees(plan, his_plan, cut):
    """A chosen plan agrees with the recorded one when it is the recorded line up to the plan's own end (labels equal)."""
    if plan is None:
        return None
    n = len(plan)
    if cut in ('end_turn', 'attack', 'end of turn'):
        return list(plan) == list(his_plan)
    return list(plan) == list(his_plan[:n])


# ---------------------------------------------------------------------------------------------------------------------------------- CLI
def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)

    def common(p):
        p.add_argument('--positions', default=DEFAULT_POSITIONS)
        p.add_argument('--decks', default=DEFAULT_DECKS)
        p.add_argument('--ids', nargs='*')
        p.add_argument('--id')
        p.add_argument('--set', choices=['diag14', 'stageA'])
        p.add_argument('--world-seed', type=int, default=1)
        p.add_argument('--max-plans', type=int, help='cap on plans listed per position (default 2000, reported when hit)')
        p.add_argument('--compact-above', type=int, default=COMPACT_ABOVE, help='more plans than this: short one-line form')

    p = sub.add_parser('plans'); common(p)
    p.add_argument('--json', action='store_true')
    p = sub.add_parser('coverage', help="check that each position's recorded plan is among the listed plans (completeness of the plan list)"); common(p)
    p = sub.add_parser('prompt'); common(p)
    p.add_argument('--order', default='forward')
    p.add_argument('--show', action='store_true', help='print the whole prompt (default: print its size only)')
    p = sub.add_parser('judge'); common(p)
    p.add_argument('--order', default='forward')
    p.add_argument('--live', action='store_true', help='really call the API (default: dry run)')
    p.add_argument('--max-calls', type=int, default=1, help='hard cap on API calls in this invocation')
    p.add_argument('--model', default=MODEL)
    p.add_argument('--temperature', type=float)
    p.add_argument('--out')
    p = sub.add_parser('run'); common(p)
    p.add_argument('--bot', required=True)
    p.add_argument('--seeds', default='1')
    p.add_argument('--order', default='forward')
    p.add_argument('--live', action='store_true')
    p.add_argument('--max-calls', type=int, default=1)
    p.add_argument('--model', default=MODEL)
    p.add_argument('--out')
    p = sub.add_parser('score')
    p.add_argument('--results', required=True)
    p.add_argument('--positions', default=DEFAULT_POSITIONS)
    p.add_argument('--decks', default=DEFAULT_DECKS)
    a = ap.parse_args(argv)

    if a.cmd == 'score':
        positions = load_positions(a.positions)
        rows = [json.loads(l) for l in open(a.results) if l.strip()]
        pids = sorted({r['position'] for r in rows})
        recs = list_plans(pids, a.positions, a.decks)
        his = match_plans([(i, i, positions[i]['his_plan']) for i in pids if positions[i].get('his_plan')], recs, a.positions, a.decks)
        tot = ok = 0
        for r in rows:
            his_n = his.get(r['position'], (None, None))[0]
            ag = None if (his_n is None or r.get('plan_number') is None) else r['plan_number'] == his_n
            if ag is not None:
                tot += 1
                ok += bool(ag)
            print(f"{r['position']:28} {r['bot']:6} seed={r.get('seed')} plan {r.get('plan_number')} / recorded {his_n} agrees={ag}")
        print(f'agreement {ok}/{tot}: same listed plan as the recorded one (old positions only: a development check, not evidence)')
        return 0

    positions = load_positions(a.positions)
    ids = resolve_ids(a, positions)
    if not ids:
        sys.exit('no positions: give --ids, --id or --set')

    if a.cmd == 'plans':
        recs = list_plans(ids, a.positions, a.decks, a.world_seed, a.max_plans)
        if a.json:
            print(json.dumps(recs))
            return 0
        print(f"{'position':28} {'plans':>6} {'found':>6} {'capped':>6} {'nodes':>7}   attack/chance/end_turn/other")
        for i in ids:
            r = recs.get(i)
            if not r or r.get('kind') != 'plans':
                print(f'{i:28} PROBLEM {r}')
                continue
            c = {}
            for p in r['plans']:
                c[p['end']] = c.get(p['end'], 0) + 1
            print(f"{i:28} {r['n_plans']:6} {r['total_found']:6} {str(r['capped']):>6} {r['nodes']:7}   {c.get('attack', 0)}/{c.get('chance', 0)}/{c.get('end_turn', 0)}/{c.get('opponent_choice', 0)}")
        return 0

    if a.cmd == 'coverage':
        recs = list_plans(ids, a.positions, a.decks, a.world_seed, a.max_plans)
        hit = 0
        usable = 0
        have = [i for i in ids if positions[i].get('his_plan') and recs.get(i, {}).get('kind') == 'plans']
        matched = match_plans([(i, i, positions[i]['his_plan']) for i in have], recs, a.positions, a.decks)
        for i in ids:
            if i not in have:
                print(f'{i:30} no recorded plan or no plan list')
                continue
            usable += 1
            n, err = matched[i]
            hit += n is not None
            print(f"{i:30} {'is plan ' + str(n) if n else 'NOT LISTED':14} of {recs[i]['n_plans']:4}  {'' if n else err}  his={positions[i]['his_plan']}")
        print(f'recorded plan is one of the listed plans (replayed through the engine, state by state): {hit}/{usable}')
        return 0

    recs = list_plans(ids, a.positions, a.decks, a.world_seed, a.max_plans) if a.cmd in ('prompt', 'judge') or getattr(a, 'bot', '') == 'judge' else {}

    if a.cmd == 'prompt':
        for i in ids:
            system, user, shown = render_prompt(positions[i], recs[i], a.order, a.decks, a.compact_above)
            n = estimate_tokens(system, user)
            print(f'### {i}: {len(shown)} plans, prompt about {n} tokens ({len(system) + len(user)} characters)')
            if a.show:
                print('--- SYSTEM\n' + system + '\n--- USER\n' + user)
        return 0

    out_f = open(a.out, 'a', encoding='utf-8') if getattr(a, 'out', None) else None
    calls = 0

    def emit(r):
        line = json.dumps(r, ensure_ascii=False)
        print(line if out_f is None else f"{r['position']} {r['bot']} {'plan ' + str(r.get('plan_number')) if r['bot'] == 'judge' else ''} -> {r['plan']}")
        if out_f:
            out_f.write(line + '\n')
            out_f.flush()

    if a.cmd == 'judge' or (a.cmd == 'run' and a.bot == 'judge'):
        total = 0.0
        for i in ids:
            if a.live and calls >= a.max_calls:
                print(f'stopped: --max-calls {a.max_calls} reached', file=sys.stderr)
                break
            r, system, user = judge_one(i, positions, recs, a.order, a.live, a.model, getattr(a, 'temperature', None), a.decks, a.compact_above)
            if not a.live:
                print(f"[dry run] {i}: {r['n_plans']} plans, prompt about {r['prompt_tokens_estimate']} tokens (estimate). Nothing was sent.")
            else:
                calls += 1
                total += r['cost']['usd']
            emit(r)
        if a.live:
            print(f'{calls} call(s), about ${total:.4f} ({PRICE_NOTE})', file=sys.stderr)
        return 0

    if a.cmd == 'run':
        seeds = [int(x) for x in a.seeds.split(',')]
        plan_lists = list_plans(ids, a.positions, a.decks, a.world_seed, a.max_plans)
        for r in run_pg_pos(a.bot, ids, seeds, plan_lists, a.positions, a.decks):
            emit(r)
        return 0
    return 0


if __name__ == '__main__':
    sys.exit(main())
