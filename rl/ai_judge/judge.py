def record(position, bot, plan, cut, **extra):
    r = {'schema': SCHEMA, 'position': position, 'bot': bot, 'seed': None, 'plan': plan, 'cut': cut}
    r.update(extra)
    return r


def judge_one(pid, positions, recs, order, live, model, temperature=None, decks_dir=DEFAULT_DECKS, compact_above=COMPACT_ABOVE, max_tokens=MAX_TOKENS, prompt_version='v1', allow_capped=False):
    pos, rec = positions[pid], recs[pid]
    if live and rec['capped'] and not allow_capped:
        raise SystemExit(f"{pid}: the plan list is capped ({rec['n_plans']} of at least {rec['total_found']} plans): it is not every legal choice, so a formal judge call is refused "
                         "(--allow-capped only for experiments; such a record is never `frozen`)")
    system, user, shown = render_prompt(pos, rec, order, decks_dir, compact_above, prompt_version)
    est = estimate_tokens(system, user, 'compact' if len(shown) > compact_above else 'full')
    frozen = (model == FROZEN['model'] and prompt_version == FROZEN['prompt_version'] and order == FROZEN['order'] and compact_above == FROZEN['compact_above']
              and max_tokens == FROZEN['max_tokens'] and temperature == FROZEN['temperature'] and not rec['capped']
              and rec.get('world_seed') == FROZEN['plan_world_seed']
              and rec.get('limits') == {k: FROZEN[k] for k in ('max_plans', 'max_nodes', 'max_steps')})
    base = dict(order=order, n_plans=len(shown), capped=rec['capped'], total_plans_found=rec['total_found'], model=model, prompt_tokens_estimate=est, dry_run=not live,
                prompt_form='compact' if len(shown) > compact_above else 'full', prompt_version=prompt_version, frozen=frozen,
                prompt_sha256=hashlib.sha256((system + '\n\0\n' + user).encode('utf-8')).hexdigest()[:16])
    if not live:
        return record(pid, 'judge', None, None, plan_number=None, reason=None, cost=None, **base), system, user
    text, usage, secs, model_used, extra = call_claude(system, user, model, max_tokens=max_tokens, temperature=temperature)
    parsed = parse_choice(text, len(shown))
    if not parsed['ok'] and extra.get('stop_reason') == 'max_tokens':
        parsed['error'] = f"{parsed['error']}; the reply was cut at max_tokens={max_tokens} (reasoning used it up): raise --max-tokens"
    plan = shown[parsed['plan']] if parsed['ok'] else None
    r = record(pid, 'judge', plan['labels'] if plan else None, plan['end'] if plan else None, plan_number=plan['n'] if plan else None, shown_number=parsed['plan'],
               reason=parsed['reason'], parse_error=parsed['error'], raw=text, seconds=secs, cost=cost_of(model_used, usage), **extra, **base)
    return r, system, user


# ---------------------------------------------------------------------------------------------------------------------------------- bots through pg_pos
def run_pg_pos(bot, ids, seeds, recs, positions_path=DEFAULT_POSITIONS, decks_dir=DEFAULT_DECKS, bin_path=PG_POS_BIN):
    """km3 / kx3 (any bot code pg_pos knows) on positions. pg_pos plays the bot's whole turn; the record keeps what it played (`plan_full`) and the same
    plan in the judge's terms (`plan`: cut after the first chance step, nothing after an attack) with the listed plan's number."""
    rows = []
    for pid in ids:
        cmd = [bin_path, '--positions', positions_path] + deck_args(decks_dir) + ['--seeds', ','.join(map(str, seeds)), '--bot', bot, '--only', pid]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            sys.exit(f'{bin_path} failed on {pid} (exit {r.returncode}): {r.stderr[-800:]}')
        got = [json.loads(line) for line in r.stdout.splitlines()]
        problems = [j for j in got if j.get('problems')]
        if problems:
            sys.exit(f'{bin_path} reports a problem with position {pid}: {problems[0].get("problems")}')
        free = [j for j in got if j.get('kind') == 'free' and j.get('id') == pid]
        seen = sorted(j['seed'] for j in free)
        if seen != sorted(seeds):
            sys.exit(f'{bot} on {pid}: expected exactly one free-play row for each of seeds {sorted(seeds)}, got {seen}')
        rows += [(pid, j) for j in free]
    matched = match_plans([(pid, f"{pid}|{j['seed']}", j['plan']) for pid, j in rows], recs, positions_path, decks_dir)
    out = []
    for pid, j in rows:
        n, err = matched[f"{pid}|{j['seed']}"]
        plan = canonical_plan(j['plan'], recs[pid])
        end = recs[pid]['plans'][n - 1]['end'] if n else None
        rec = record(pid, bot, plan, end, plan_number=n, match_error=err, plan_full=j['plan'], pg_pos_cut=j['cut'], cost=None, dry_run=False)
        rec['seed'] = j['seed']
        out.append(rec)
    return out


def _norm(l):  # recorded plans name a Place or an Ability without the slot number
    return l.split('@')[0] if l.startswith(('Place:', 'Ability')) else l


def canonical_plan(labels, rec):
    """A bot's or a recording's move list, put in the plan list's terms: cut after its first chance step (the judge decides again there), and nothing
    after an attack. The closing EndTurn of a plan that did not attack stays out of the comparison key (see match_plan)."""
    chance_labels = {_norm(p['labels'][-1]) for p in rec['plans'] if p['end'] == 'chance'}
    out = []
    for l in labels:
        out.append(l)
        if _norm(l) in chance_labels or l.startswith('Attack:'):
            break
    return out


def replay(items, positions_path=DEFAULT_POSITIONS, decks_dir=DEFAULT_DECKS, world_seed=1, bin_path=PLANS_BIN):
    """Replays move lists through the engine (the same step rules as the plan lister) and returns {tag: [plan keys]}. items = [(position id, tag, labels)].
    A move list is followed up to its first chance step or its attack; a list that ends first is ended with End the turn; a step the list does not name
    but the engine forces (one legal action) is taken. A list that cannot be followed gets an error text instead of keys."""
    import tempfile
    with tempfile.NamedTemporaryFile('w', suffix='.jsonl', delete=False) as f:
        for pid, tag, labels in items:
            f.write(json.dumps({'id': pid, 'tag': tag, 'labels': [concrete_label(l) for l in labels]}) + '\n')
        path = f.name
    try:
        cmd = [bin_path, '--positions', positions_path] + deck_args(decks_dir) + ['--world-seed', str(world_seed), '--replay', path]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            sys.exit(f'judge_plans --replay failed: {r.stderr[-1500:]}')
    finally:
        os.unlink(path)
    out = {}
    for line in r.stdout.splitlines():
        j = json.loads(line)
        if j['tag'] in out:
            sys.exit(f"judge_plans --replay answered tag {j['tag']} twice")
        out[j['tag']] = j['keys'] if j['ok'] else j['error']
    tags = [t for _, t, _ in items]
    if len(set(tags)) != len(tags):
        sys.exit('replay: duplicate tags in the request')
    missing = [t for t in tags if t not in out]
    if missing:
        sys.exit(f'judge_plans --replay gave no answer for {missing[:5]}')
    return out


class AmbiguousPlan(ValueError):
    """A move list that fits more than one listed plan (for example a bare recorded name that fits several targets)."""


def number_for(rec, keys):
    """The ONE listed plan whose key is among `keys`; None when the list could not be followed (keys is an error text) or reaches no listed plan.
    Raises AmbiguousPlan when the keys fit more than one listed plan: a bare name is never resolved to the first target."""
    if not isinstance(keys, list):
        return None
    by_key = {p['key']: p['n'] for p in rec['plans']}
    hit = sorted({by_key[k] for k in keys if k in by_key})
    if len(hit) > 1:
        raise AmbiguousPlan(f'the move list fits {len(hit)} different listed plans {hit[:6]}: name the target (Name#{{json}} label)')
    return hit[0] if hit else None


_LEGACY = re.compile(r'^([A-Za-z]\w*)\{(.*)\}$')


def concrete_label(label):
    """One canonical concrete action label across packages: Name#<compact JSON, keys sorted>. A legacy `Name{field:value,...}` label is converted when every
    value is an integer, true/false or a bare word (lossless); anything else is rejected with a clear error. Short names and Name#JSON pass unchanged."""
    m = _LEGACY.match(label)
    if not m:
        return label
    obj = {}
    body = m.group(2).strip()
    for part in ([x.strip() for x in body.split(',')] if body else []):
        if ':' not in part:
            raise ValueError(f'unsupported legacy concrete label {label!r}: cannot read {part!r}')
        k, v = (x.strip() for x in part.split(':', 1))
        if re.fullmatch(r'-?\d+', v):
            obj[k] = int(v)
        elif v in ('true', 'false'):
            obj[k] = v == 'true'
        elif re.fullmatch(r'"[^"\\]*"', v):
            obj[k] = v[1:-1]
        else:
            raise ValueError(f'unsupported legacy concrete label {label!r}: value {v!r} is not an integer, boolean or quoted string')
    return f"{m.group(1)}#{json.dumps(obj, sort_keys=True, separators=(',', ':'))}"


def match_plans(items, recs, positions_path=DEFAULT_POSITIONS, decks_dir=DEFAULT_DECKS):
    """items = [(position id, tag, labels)] -> {tag: (plan number or None, error text or None)}."""
    keys = replay(items, positions_path, decks_dir)
    out = {}
    for pid, tag, _ in items:
        k = keys.get(tag)
        try:
            n = number_for(recs[pid], k)
        except AmbiguousPlan as e:
            out[tag] = (None, f'ambiguous: {e}')
            continue
        out[tag] = (n, k if isinstance(k, str) else (None if n else 'reaches no listed plan (capped list?)'))
    return out


def agrees(plan, his_plan, cut):
    """A chosen plan agrees with the recorded one when it is the recorded line up to the plan's own end (labels equal)."""
    if plan is None:
        return None
    n = len(plan)
    if cut in ('end_turn', 'attack', 'end of turn'):
        return list(plan) == list(his_plan)
    return list(plan) == list(his_plan[:n])


def fingerprint():
    """What 'the frozen prompt' means in bytes: the prompt texts, the code that lays a prompt out, and the frozen settings. tests/test_frozen.py compares this
    with FROZEN.json, so any later edit to the prompt shows up as a failing test until a new freeze is recorded on purpose."""
    parts = [SYSTEM, ANSWER_FORMAT, COMPACT_LEGEND, SYSTEM_V2, ANSWER_FORMAT_V2, json.dumps(GROUP_TITLES, sort_keys=True),
             inspect.getsource(render_prompt), inspect.getsource(_plan_text), inspect.getsource(_plan_compact), inspect.getsource(order_plans),
             json.dumps(FROZEN, sort_keys=True)]
    return hashlib.sha256('\n\0\n'.join(parts).encode('utf-8')).hexdigest()


