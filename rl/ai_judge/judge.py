def run_pg_pos(bot, ids, seeds, recs, positions_path=DEFAULT_POSITIONS, decks_dir=DEFAULT_DECKS, bin_path=PG_POS_BIN):
    """km3 (any bot code of the form k<number> that pg_pos knows) on positions. pg_pos plays the bot's turn up to its first draw card or the end of the turn
    (`pg_pos_cut`: 'first draw' | 'end of turn'); the record keeps what it played (`plan_full`) and the same plan in the judge's terms (`plan`: cut after the first
    chance step, nothing after an attack) with the listed plan's number. Other step bots (kx3, the playout pilot) are NOT played by the frozen baseline executable."""
    if not re.fullmatch(r'km?\d+', bot):
        sys.exit(f"the frozen baseline executable (pg_pos) plays the minimax bots coded k<number> / km<number> (k3, km3, km1, ...), not {bot!r}: another step bot (kx3, "
                 "the playout pilot) needs its own frozen executable and identity")
    rows = []
    pg_sha = file_sha256(bin_path)
    for pid in ids:
        cmd = [bin_path, '--positions', positions_path] + deck_args(decks_dir) + ['--seeds', ','.join(map(str, seeds)), '--bot', bot, '--only', pid]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            sys.exit(f'{bin_path} failed on {pid} (exit {r.returncode}): {r.stderr[-800:]}')
        got = [json.loads(line) for line in r.stdout.splitlines()]
        problems = [j for j in got if j.get('problems')]
        if problems:
            sys.exit(f'{bin_path} reports a problem with position {pid}: {problems[0].get("problems")}')
        free = [j for j in got if j.get('kind') == 'free' and j.get('id') == pid]
        seen = sorted(j['seed'] for j in free)
        if seen != sorted(seeds):
            sys.exit(f'{bot} on {pid}: expected exactly one free-play row for each of seeds {sorted(seeds)}, got {seen}')
        rows += [(pid, j) for j in free]
    matched = match_plans([(pid, f"{pid}|{j['seed']}", j['plan']) for pid, j in rows], recs, positions_path, decks_dir)
    out = []
    for pid, j in rows:
        n, err = matched[f"{pid}|{j['seed']}"]
        plan = canonical_plan(j['plan'], recs[pid])
        end = recs[pid]['plans'][n - 1]['end'] if n else None
        rec = record(pid, bot, plan, end, plan_number=n, match_error=err, plan_full=j['plan'], pg_pos_cut=j['cut'], pg_pos_sha256=pg_sha, cost=None, dry_run=False,
                     plan_key=(recs[pid]['plans'][n - 1]['key'] if n else None), plan_list_sha256=plan_list_sha256(recs[pid]))
        rec['seed'] = j['seed']
        out.append(rec)
    return out


def _norm(l):  # recorded plans name a Place or an Ability without the slot number
    return l.split('@')[0] if l.startswith(('Place:', 'Ability')) else l


def canonical_plan(labels, rec):
    """A bot's or a recording's move list, put in the plan list's terms: cut after its first chance step (the judge decides again there), and nothing
    after an attack. The closing EndTurn of a plan that did not attack stays out of the comparison key (see match_plan)."""
    chance_labels = {_norm(p['labels'][-1]) for p in rec['plans'] if p['end'] == 'chance'}
    out = []
    for l in labels:
        out.append(l)
        if _norm(l) in chance_labels or l.startswith('Attack:'):
            break
    return out


def replay(items, positions_path=DEFAULT_POSITIONS, decks_dir=DEFAULT_DECKS, world_seed=1, bin_path=PLANS_BIN):
    """Replays move lists through the engine (the same step rules as the plan lister) and returns {tag: [plan keys]}. items = [(position id, tag, labels)].
    A move list is followed up to its first chance step or its attack; a list that ends first is ended with End the turn; a step the list does not name
    but the engine forces (one legal action) is taken. A list that cannot be followed gets an error text instead of keys."""
    import tempfile
    with tempfile.NamedTemporaryFile('w', suffix='.jsonl', delete=False) as f:
        for pid, tag, labels in items:
            f.write(json.dumps({'id': pid, 'tag': tag, 'labels': [concrete_label(l) for l in labels]}) + '\n')
        path = f.name
    try:
        cmd = [bin_path, '--positions', positions_path] + deck_args(decks_dir) + ['--world-seed', str(world_seed), '--replay', path]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode:
            sys.exit(f'judge_plans --replay failed: {r.stderr[-1500:]}')
    finally:
        os.unlink(path)
    out = {}
    for line in r.stdout.splitlines():
        j = json.loads(line)
        if j['tag'] in out:
            sys.exit(f"judge_plans --replay answered tag {j['tag']} twice")
        out[j['tag']] = j['keys'] if j['ok'] else j['error']
    tags = [t for _, t, _ in items]
    if len(set(tags)) != len(tags):
        sys.exit('replay: duplicate tags in the request')
    missing = [t for t in tags if t not in out]
    if missing:
        sys.exit(f'judge_plans --replay gave no answer for {missing[:5]}')
    return out


class AmbiguousPlan(ValueError):
    """A move list that fits more than one listed plan (for example a bare recorded name that fits several targets)."""


def number_for(rec, keys):
    """The ONE listed plan whose key is among `keys`; None when the list could not be followed (keys is an error text) or reaches no listed plan.
    Raises AmbiguousPlan when the keys fit more than one listed plan: a bare name is never resolved to the first target."""
    if not isinstance(keys, list):
        return None
    by_key = {p['key']: p['n'] for p in rec['plans']}
    hit = sorted({by_key[k] for k in keys if k in by_key})
    if len(hit) > 1:
        raise AmbiguousPlan(f'the move list fits {len(hit)} different listed plans {hit[:6]}: name the target (Name#{{json}} label); for a Place / Ability label give its slot '
                            f'(Place:Axew@3), or list each plan it fits as a separate accepted entry of the point\'s reference list')
    return hit[0] if hit else None


_LEGACY = re.compile(r'^([A-Za-z]\w*)\{(.*)\}$')


def _compact(obj):
    return json.dumps(obj, sort_keys=True, separators=(',', ':'), ensure_ascii=False)  # the form serde_json prints: no spaces, keys sorted, raw UTF-8


def _sorted_energies(obj):
    """A list of Energy types under the key `energies` is a multiset (which Energy a retreat pays or an attack discards): its order is not part of the action, so it is
    sorted in the canonical label (the lister does the same, in plans/src/main.rs canon_label)."""
    if isinstance(obj, dict) and isinstance(obj.get('energies'), list) and all(isinstance(e, str) for e in obj['energies']):
        return {**obj, 'energies': sorted(obj['energies'])}
    return obj


def concrete_label(label):
    """One canonical concrete action label across packages: Name#<compact JSON, keys sorted>. A `Name#{json}` label is re-written in that form, so JSON key
    order and spacing never matter (its content must be valid JSON, else ValueError). A legacy `Name{field:value,...}` label is converted when every
    value is an integer, true/false or a quoted string (lossless); anything else is rejected with a clear error. Short names pass unchanged."""
    name, hash_, js = label.partition('#')
    if hash_ and re.fullmatch(r'[A-Za-z]\w*', name):
        try:
            canon = f'{name}#{_compact(_sorted_energies(json.loads(js)))}'
            canon.encode('utf-8')  # a lone surrogate escape ("\ud800") parses in Python but not in the lister: refuse it here
            return canon
        except (ValueError, RecursionError):
            raise ValueError(f'concrete label {label!r}: the part after # is not valid JSON') from None
    m = _LEGACY.match(label)
    if not m:
        return label
    obj = {}
    body = m.group(2).strip()
    for part in ([x.strip() for x in body.split(',')] if body else []):
        if ':' not in part:
            raise ValueError(f'unsupported legacy concrete label {label!r}: cannot read {part!r}')
        k, v = (x.strip() for x in part.split(':', 1))
        if re.fullmatch(r'-?\d+', v):
            obj[k] = int(v)
        elif v in ('true', 'false'):
            obj[k] = v == 'true'
        elif re.fullmatch(r'"[^"\\]*"', v):
            obj[k] = v[1:-1]
        else:
            raise ValueError(f'unsupported legacy concrete label {label!r}: value {v!r} is not an integer, boolean or quoted string')
    return f'{m.group(1)}#{_compact(obj)}'


def match_plans(items, recs, positions_path=DEFAULT_POSITIONS, decks_dir=DEFAULT_DECKS):
    """items = [(position id, tag, labels)] -> {tag: (plan number or None, error text or None)}. A move list that is not a non-empty list of readable text labels
    is answered with an error text for that item alone (it never takes the other items down)."""
    out, good = {}, []
    for pid, tag, labels in items:
        if not isinstance(labels, list) or not labels or not all(isinstance(l, str) for l in labels):
            out[tag] = (None, 'unreadable move list: it must be a non-empty list of text labels')
            continue
        try:
            for l in labels:
                concrete_label(l)
        except ValueError as e:
            out[tag] = (None, f'unreadable move list: {e}')
            continue
        good.append((pid, tag, labels))
    keys = replay(good, positions_path, decks_dir) if good else {}
    for pid, tag, _ in good:
        k = keys.get(tag)
        try:
            n = number_for(recs[pid], k)
        except AmbiguousPlan as e:
            out[tag] = (None, f'ambiguous: {e}')
            continue
        out[tag] = (n, k if isinstance(k, str) else (None if n else 'reaches no listed plan (capped list?)'))
    return out


def normalize_full(labels):
    """The canonical form of a COMPLETE move list (full-plan agreement): every label in the Name#JSON form (Energy lists sorted); the plan ends at its Attack (what
    follows an attack is the engine's bookkeeping and the opponent's turn, as in canonical_plan: real bot lists carry End the turn, ResolveAttackRetaliation ...),
    else without a closing End the turn. Slots are kept. Raises ValueError for a label that cannot be read."""
    out = [concrete_label(l) for l in labels]
    for i, l in enumerate(out):
        if l.startswith('Attack:'):
            return out[:i + 1]
    if out and out[-1] == 'EndTurn':
        out.pop()
    return out


def _label_eq(x, y):
    """x (played) against y (accepted/recorded): equal, or y is a Place / Ability label without its slot number (it fits any slot, as in the engine replay)."""
    return x == y or (y.startswith(('Place:', 'Ability')) and '@' not in y and x.split('@')[0] == y)


def full_match(row_labels, ref_labels, rec):
    """The REMAINDER of two COMPLETE move lists after the plan's own end (the first chance event; for a plan that goes to its Attack or End the turn there is none).
    The part up to that end is compared by plan identity elsewhere (the row and the accepted list reach the same listed plan: order of moves does not matter there);
    what follows a chance event cannot be replayed, so it is compared label by label, in order, in canonical form (closing End the turn dropped, the plan ends at its
    Attack, a reference Place / Ability label without its slot fits any slot). Raises ValueError for a label that cannot be read."""
    def remainder(labels):
        labels = [concrete_label(l) for l in labels]
        head = canonical_plan(labels, rec)
        if head and head[-1].startswith('Attack:'):
            return []  # the plan ends at its attack: whatever the list carries after it is bookkeeping, not a decision of the turn
        return normalize_full(labels[len(head):])
    a, b = remainder(row_labels), remainder(ref_labels)
    return len(a) == len(b) and all(_label_eq(x, y) for x, y in zip(a, b))


def label_roundtrip(recs, positions_path=DEFAULT_POSITIONS, decks_dir=DEFAULT_DECKS):
    """Do the plans' own labels name them? For every plan the labels are replayed through the engine; they must reach exactly that plan's key. Returns
    {position: {n_plans, unique, ambiguous, unfollowable}}. A plan whose labels fit several plans cannot be named by a bot's or a recording's move list (such a
    list is AMBIGUOUS and fails the formal comparison), and the judge is shown plans that look identical."""
    items = [(pid, f"{pid}|{p['n']}", p['labels']) for pid, rec in recs.items() for p in rec['plans']]
    keys = replay(items, positions_path, decks_dir) if items else {}
    out = {pid: {'n_plans': len(rec['plans']), 'unique': 0, 'ambiguous': 0, 'unfollowable': 0} for pid, rec in recs.items()}
    for pid, tag, _ in items:
        n, k = int(tag.rsplit('|', 1)[1]), keys[tag]
        if not isinstance(k, list):
            out[pid]['unfollowable'] += 1
            continue
        try:
            got = number_for(recs[pid], k)
        except AmbiguousPlan:
            out[pid]['ambiguous'] += 1
            continue
        out[pid]['unique' if got == n else 'ambiguous'] += 1
    return out


def agrees(plan, his_plan, cut):
    """A chosen plan agrees with the recorded one when it is the recorded line up to the plan's own end (labels equal)."""
    if plan is None:
        return None
    n = len(plan)
    if cut in ('end_turn', 'attack', 'end of turn'):
        return list(plan) == list(his_plan)
    return list(plan) == list(his_plan[:n])


def fingerprint():
    """What 'the frozen prompt' means in bytes: the prompt texts, the code that lays a prompt out, and the frozen settings. tests/test_frozen.py compares this
    with FROZEN.json, so any later edit to the prompt shows up as a failing test until a new freeze is recorded on purpose."""
    parts = [SYSTEM, ANSWER_FORMAT, COMPACT_LEGEND, SYSTEM_V2, ANSWER_FORMAT_V2, json.dumps(GROUP_TITLES, sort_keys=True),
             inspect.getsource(render_prompt), inspect.getsource(_plan_text), inspect.getsource(_plan_compact), inspect.getsource(order_plans),
             json.dumps(FROZEN, sort_keys=True)]
    return hashlib.sha256('\n\0\n'.join(parts).encode('utf-8')).hexdigest()


