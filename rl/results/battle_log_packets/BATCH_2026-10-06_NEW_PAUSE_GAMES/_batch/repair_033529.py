"""Apply the two frozen independent repairs without rebuilding the worker packet."""
import copy
import hashlib
import json
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

B = Path(__file__).resolve().parent
P = B/'20261005_033529000_iOS'
check = json.loads((P/'independent_sol/CHECK_RESULT.json').read_text(encoding='utf-8'))
assert check['accepted'] is False
assert {r['repair_id'] for r in check['required_repairs']} == {'R1', 'R2'}
backup = P/'original_before_R1_R2'
assert not backup.exists() and not (P/'LEAD_ACCEPTANCE.json').exists()
for name, expected in check['checked_input_sha256'].items():
    assert hashlib.sha256((P/name).read_bytes()).hexdigest() == expected, name
backup.mkdir()
for name in check['checked_input_sha256']:
    shutil.copy2(P/name, backup/Path(name).name)
ledger = json.loads((P/'TURN_LEDGER.json').read_text(encoding='utf-8'))

def parent(path):
    assert path.startswith('$.turns[')
    keys = [word if word else int(index) for word, index in re.findall(r'([A-Za-z_][A-Za-z_0-9]*)|\[(\d+)\]', path[2:])]
    current = ledger
    for key in keys[:-1]:
        current = current[key]
    return current, keys[-1]

changes = []
for repair in check['required_repairs']:
    for field in repair['affected_fields']:
        container, key = parent(field['json_path'])
        before = copy.deepcopy(container[key])
        if repair['repair_id'] == 'R1':
            assert before == field['before']
            container[key] = field['required_value']
            container['current_status'] = 'observed_absent_at_selected_boundary'
            container['basis'] = 'Large current Energy sphere visibly empty at the selected starting frame; small next preview remains visible. Later generation is separately bounded.'
            container['energy_generation_transition'] = {
                'source_local_window_seconds':field['generation_bound_seconds'],
                'later_this_turn':before,
                'evidence_ids':[field['evidence_id'],field['later_generated_evidence_id']],
                'basis':'Absent at first bound and generated by the later retained frame; exact generation instant was not measured.'}
        else:
            assert before is None
            container[key] = 'none'
            container[key+'_observation'] = {
                'status':'observed_absent',
                'basis':'No attached Tool visible on the named Pokemon in the linked native boundary.' if field['kind'] == 'Tool' else 'No Stadium visible in the linked early boundary, before the observed Arena play on Turn2.',
                'evidence_ids':field['evidence_ids']}
        changes.append({'repair_id':repair['repair_id'],'json_path':field['json_path'],'before':before,'after':copy.deepcopy(container[key])})
assert sum(c['repair_id'] == 'R1' for c in changes) == 5
assert sum(c['repair_id'] == 'R2' for c in changes) == 115
(P/'TURN_LEDGER.json').write_text(json.dumps(ledger,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
review = (P/'REVIEW.md').read_text(encoding='utf-8')
assert review.count('Arena remains throughout.') == 1
review = review.replace('Arena remains throughout.', 'Arena remains after its observed Turn 2 play at 69 seconds; the earlier three retained boundaries show no Stadium.')
review += '\nIndependent correction: selected starting frames 46, 81.5, 131.5, 232.8 and 310.8 seconds precede current Energy generation. Their large spheres are recorded empty, with the typed next previews preserved and later generation bounded separately. Explicit Tool and early Stadium absence now use none plus field-specific observed-absence evidence, rather than ambiguous null. Intact hand selection, actions, attachments and outcomes are unchanged.\n'
(P/'REVIEW.md').write_text(review,encoding='utf-8')
coverage = (P/'COVERAGE.md').read_text(encoding='utf-8')
coverage += '\nThe independent Energy-boundary correction uses existing native evidence at 46/49, 81.5/82.5, 131.5/134.5, 232.8/235.8 and 310.8/313.8 seconds. No source phase was added or removed. Early Stadium absence is distinct from Arena continuity after its Turn2 play at 69 seconds. The rejected inputs are preserved in original_before_R1_R2.\n'
(P/'COVERAGE.md').write_text(coverage,encoding='utf-8')
receipt = {'repaired_utc':datetime.now(timezone.utc).isoformat(),'lead':'/root','source_sha256':check['source_sha256'],'initial_independent_report':'independent_sol/CHECK_RESULT.json','original_input_sha256':check['checked_input_sha256'],'original_input_backup':'original_before_R1_R2','required_repairs_applied':['R1','R2'],'changes':changes,'related_checker_prose_disposition':'Checker confirmed Arena is first observed played at69s; qualify continuity to begin after Turn2 play.','retained_source_evidence_changed':False,'independent_recheck_required':True}
(P/'INDEPENDENT_CORRECTIONS.json').write_text(json.dumps(receipt,indent=2)+'\n',encoding='utf-8')
result = subprocess.run([sys.executable,str(B/'validate_packet.py'),str(P)],capture_output=True,text=True,encoding='utf-8',check=True)
structure = json.loads(result.stdout)
assert structure['structural_pass'] is True
(P/'ROOT_REPAIR_STRUCTURE_CHECK.json').write_text(json.dumps(structure,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'required_repairs_applied':['R1','R2'],'corrected_fields':len(changes),'structural_pass':True,'independent_recheck_required':True}))
