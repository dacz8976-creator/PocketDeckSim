def parent(path):
    keys = [word if word else int(index) for word, index in re.findall(r'([A-Za-z_][A-Za-z_0-9]*)|\[(\d+)\]', path[2:])]
    current = ledger
    for key in keys[:-1]:
        current = current[key]
    return current, keys[-1]

