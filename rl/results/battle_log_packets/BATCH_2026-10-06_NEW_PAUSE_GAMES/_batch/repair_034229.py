def indexed(seconds, folder, observation, turn):
    eid = 'f_' + f'{seconds:07.2f}'.replace('.', '_')
    if eid in frames:
        row = frames[eid]
    else:
        row = copy.deepcopy(frames['f_0090_00'])
        base = f't{seconds:07.2f}'
        full = P / folder / (base + '.jpg')
        assert full.exists(), full
        img = Image.open(full)
        assert img.size == (1170, 2532)
        bottom = full.with_name(base + '_bottom.jpg')
        top = full.with_name(base + '_top.jpg')
        img.crop((0, 2025, 1170, 2532)).save(bottom, quality=95)
        img.crop((0, 0, 1170, 730)).save(top, quality=95)
        row.update(evidence_id=eid, requested_source_seconds=seconds,
                   full_frame_path=full.relative_to(P).as_posix(),
                   turn_number=turn, who_played='owner' if turn == 7 else 'opponent')
        row['bottom_crop']['path'] = bottom.relative_to(P).as_posix()
        row['top_crop']['path'] = top.relative_to(P).as_posix()
        row['full_frame_sha256'] = hashlib.sha256(full.read_bytes()).hexdigest()
        row['draw_animation_end_seconds'] = None
        row['selected_for_start_hand'] = False
        row['before_first_play'] = False
        row['unzoomed'] = None
        row['hand_spread'] = None
        row['visual_inspection'] = {
            'full_frame': 'root_inspected_native_source_frame',
            'selected_hand_card_identities_verified': False,
            'bottom_crop': 'generated from root-inspected full-frame region; not selected start hand',
            'top_crop': 'generated from root-inspected full-frame region'}
        evidence['frames'].append(row)
        frames[eid] = row
        new_assets.append({'evidence_id': eid, 'full_frame_path': row['full_frame_path'], 'sha256': row['full_frame_sha256']})
    row['observation'] = observation
    return eid

